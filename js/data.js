/** 先頭3桁から割当先を引く（最も狭い範囲を優先） */
function lookupGs1Prefix(prefix3) {
  const n = parseInt(prefix3, 10);
  if (Number.isNaN(n)) return null;
  let best = null;
  for (const [lo, hi, name] of GS1_PREFIX_RANGES) {
    if (n >= lo && n <= hi) {
      if (!best || (hi - lo) < (best[1] - best[0])) best = [lo, hi, name];
    }
  }
  if (!best) return null;
  const range = best[0] === best[1]
    ? String(best[0]).padStart(3, '0')
    : String(best[0]).padStart(3, '0') + '-' + String(best[1]).padStart(3, '0');
  return { range: range, name: best[2] };
}

